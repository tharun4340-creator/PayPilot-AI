"""Invoice PDF rendering with reportlab. Uses currency codes (the base PDF font has no rupee glyph)."""
from __future__ import annotations

import io
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

NAVY = colors.HexColor("#0B1220")


def render_invoice_pdf(inv: dict, seller: dict) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm, topMargin=18 * mm, bottomMargin=18 * mm,
                            title=f"Invoice {inv['number']}", author=seller.get("name", "PayPilot AI"))
    ss = getSampleStyleSheet()
    h = ParagraphStyle("h", parent=ss["Title"], textColor=NAVY, alignment=0, fontSize=24)
    small = ParagraphStyle("s", parent=ss["Normal"], fontSize=9, textColor=colors.HexColor("#475467"))
    body = ss["Normal"]
    cur = inv["currency"]
    money = lambda v: f"{cur} {float(v):,.2f}"  # noqa: E731
    p = lambda text, style=body: Paragraph(escape(str(text)).replace("\n", "<br/>"), style)  # noqa: E731
    story = [p("INVOICE", h), p(f"No. {inv['number']}   |   Status: {inv['status']}", small), Spacer(1, 6 * mm)]
    if inv.get("is_demo"):
        story += [p("DEMO DATA - sample invoice, not a real billing document", ParagraphStyle("d", parent=body, textColor=colors.HexColor("#B54708"))), Spacer(1, 3 * mm)]
    parties = Table([[p("From", small), p("Billed to", small), p("Dates", small)],
                     [p(f"{seller.get('name', '')}\n{seller.get('email', '')}"),
                      p(f"{inv['customer_name']}\n{inv.get('customer_email') or ''}"),
                      p(f"Issued: {inv['issue_date']}\nDue: {inv['due_date']}")]], colWidths=[58 * mm, 58 * mm, 54 * mm])
    parties.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story += [parties, Spacer(1, 8 * mm)]
    rows = [["Description", "Qty", "Unit price", "Amount"]] + [
        [p(i["description"]), f"{float(i['quantity']):g}", money(i["unit_price"]), money(i["amount"])] for i in inv["items"]]
    table = Table(rows, colWidths=[78 * mm, 20 * mm, 36 * mm, 36 * mm], repeatRows=1)
    table.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), NAVY), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                               ("ALIGN", (1, 0), (-1, -1), "RIGHT"), ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#D0D5DD")),
                               ("VALIGN", (0, 0), (-1, -1), "MIDDLE")]))
    totals = Table([["Subtotal", money(inv["subtotal"])], [f"Tax ({float(inv['tax_rate']):g}%)", money(inv["tax_amount"])], ["Total due", money(inv["total"])]],
                   colWidths=[130 * mm, 40 * mm])
    totals.setStyle(TableStyle([("ALIGN", (1, 0), (1, -1), "RIGHT"), ("FONTNAME", (0, 2), (-1, 2), "Helvetica-Bold"), ("LINEABOVE", (0, 2), (-1, 2), 0.75, NAVY)]))
    story += [table, Spacer(1, 4 * mm), totals]
    if inv.get("notes"):
        story += [Spacer(1, 8 * mm), p("Notes", small), p(inv["notes"])]
    story += [Spacer(1, 12 * mm), p("Generated by PayPilot AI. Payment is only confirmed when PayPal reports it as completed.", small)]
    doc.build(story)
    return buf.getvalue()
